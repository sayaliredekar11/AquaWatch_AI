def get_demo_locations_list() -> List[Dict[str, Any]]:
    """Returns copy of all demo monitoring locations with their latest summary."""
    locations = []
    for item in DEMO_MONITORING_LOCATIONS:
        history = item.get("history", [])
        latest = history[-1] if history else None
        locations.append(
            {
                "location_id": item["location_id"],
                "water_body_id": item["location_id"],
                "name": item["name"],
                "water_body_type": item["water_body_type"],
                "location_name": item["location_name"],
                "latitude": item["latitude"],
                "longitude": item["longitude"],
                "is_demo": True,
                "notes": item["notes"],
                "latest_measured_at": latest["measured_at"] if latest else None,
                "latest_measurements": latest,
                "water_quality_status": "DEMO_EVALUATION",
                "status_reason": "Synthetic demonstration dataset for UI testing and trend visualization",
                "total_observations": len(history),
            }
        )
    return locations


def get_demo_location_by_id(location_id: str) -> Optional[Dict[str, Any]]:
    """Retrieves a single demo monitoring station by its location_id."""
    clean_id = str(location_id).strip().lower()
    for item in DEMO_MONITORING_LOCATIONS:
        if item["location_id"].lower() == clean_id:
            return item
    return None


def get_demo_location_history(
    location_id: str,
    start_date: Optional[datetime] = None,
    end_date: Optional[datetime] = None,
    limit: int = 100,
) -> Optional[List[Dict[str, Any]]]:
    """Retrieves the dated observations for a specific demo station, optionally filtered by date range."""
    loc = get_demo_location_by_id(location_id)
    if not loc:
        return None

    history = loc.get("history", [])
    filtered = []
    for rec in history:
        m_at = rec["measured_at"]
        if start_date and m_at < start_date:
            continue
        if end_date and m_at > end_date:
            continue
        filtered.append(rec)

    # Sort in ascending order by measured_at for chronological charts, capped at limit
    filtered_sorted = sorted(filtered, key=lambda x: x["measured_at"])
    return filtered_sorted[:limit]
